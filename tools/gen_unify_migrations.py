#!/usr/bin/env python3
"""
Generate the seven `fazle_` prefix-unification rename migrations.

One migration file per renamed table, numbered sequentially after the last
existing migration in `db/migrations/`.  Each file:

  * uses `ALTER TABLE IF EXISTS <old> RENAME TO <new>;`
  * renames every dependent index / constraint / sequence / trigger /
    function that carries the old prefix (name-only — definitions are
    never touched)
  * is idempotent (safe to re-run)
  * carries a rollback section as SQL comments

Usage:
    python tools/gen_unify_migrations.py [--db-objects dump.json] [--out-dir db/migrations]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from prefix_unification_map import TABLE_MAP, rename_db_object

ROOT = Path(__file__).resolve().parent.parent

# Migration file names, in the order the task's EXACT RENAMING MAP lists
# them.  The numeric prefix is computed from the last existing migration.
FILE_STEMS = [
    ("wbom_whatsapp_messages", "unify_rename_wbom_whatsapp_messages"),
    ("wbom_contacts", "unify_rename_wbom_contacts"),
    ("wbom_cash_transactions", "unify_rename_wbom_cash_transactions_archive"),
    ("wbom_employees", "unify_rename_wbom_employees_legacy"),
    ("fpe_cash_transactions", "unify_rename_fpe_cash_transactions"),
    ("fpe_employee_ledger", "unify_rename_fpe_employee_ledger"),
    ("fpe_employees", "unify_rename_fpe_employees"),
]

HEADER = """\
-- ============================================================================
-- {stem}
-- ============================================================================
-- Prefix unification: `{old}` -> `{new}`
--
-- Generated by tools/gen_unify_migrations.py — do not hand-edit.
--
-- WHAT THIS DOES
--   Renames ONE table and every dependent database object that carries the
--   legacy `wbom_` / `fpe_` prefix.  Nothing is dropped, truncated or
--   re-created: `ALTER TABLE ... RENAME TO` preserves every row, column,
--   data type, index definition, constraint definition and sequence value.
--
--   * Column names are NOT changed (HARD CONSTRAINT #4).  Columns such as
--     `wbom_employee_id` and `fpe_wa_message_id` keep their names.
--   * Index / constraint / trigger / function renames are NAME-ONLY.
--     Every definition, predicate and uniqueness rule is preserved
--     byte-for-byte, so the 4-layer duplicate-prevention behaviour
--     (queue idempotency_key, message_hash UNIQUE, image hash,
--     txn_ref idempotency) is untouched.
--   * Foreign keys pointing at this table from OTHER tables are rewritten
--     automatically by PostgreSQL when the table is renamed.
--
-- IDEMPOTENCY
--   Every statement is guarded, so this file is safe to re-run and safe on
--   a database where the table has already been renamed.
--
-- ROLLBACK
--   See the "ROLLBACK" section at the bottom of this file.  Run it in
--   reverse order (096 -> 090) to restore the pre-unification names.
-- ============================================================================

"""


def _load_objects(path: Path | None) -> dict:
    if path and path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def _merge_objects(db: dict, sql: dict) -> dict:
    """
    Merge the live-database dump with the SQL-source scan.

    The live DB shows what actually exists; the SQL scan shows what the
    migration files create (which can be a superset when a transaction
    rolled back, e.g. when the `pg_trgm` extension is unavailable).  The
    union is the safe set to rename.
    """
    merged: dict = {
        "indexes": [],
        "constraints": [],
        "sequences": [],
        "triggers": [],
    }

    seen_idx = set()
    for r in db.get("indexes", []):
        key = (r["index_name"], r["on_table"])
        if key not in seen_idx:
            seen_idx.add(key)
            merged["indexes"].append({"index_name": r["index_name"], "on_table": r["on_table"]})
    for name, table in sql.get("indexes", {}).items():
        key = (name, table)
        if key not in seen_idx:
            seen_idx.add(key)
            merged["indexes"].append({"index_name": name, "on_table": table})

    seen_con = set()
    for r in db.get("constraints", []):
        key = (r["constraint_name"], r["on_table"])
        if key not in seen_con:
            seen_con.add(key)
            merged["constraints"].append({
                "constraint_name": r["constraint_name"],
                "on_table": r["on_table"],
                "contype": r.get("contype", ""),
                "references_table": r.get("references_table"),
            })
    for name, table in sql.get("constraints", {}).items():
        key = (name, table)
        if key not in seen_con:
            seen_con.add(key)
            merged["constraints"].append({
                "constraint_name": name,
                "on_table": table,
                "contype": "",
                "references_table": None,
            })

    seen_seq = set()
    for r in db.get("sequences", []):
        if r["sequence_name"] not in seen_seq:
            seen_seq.add(r["sequence_name"])
            merged["sequences"].append({"sequence_name": r["sequence_name"], "schema": "public"})
    for name in sql.get("sequences", []):
        if name not in seen_seq:
            seen_seq.add(name)
            merged["sequences"].append({"sequence_name": name, "schema": "public"})

    seen_trg = set()
    for r in db.get("triggers", []):
        if r["trigger_name"] not in seen_trg:
            seen_trg.add(r["trigger_name"])
            merged["triggers"].append({
                "trigger_name": r["trigger_name"],
                "on_table": r["on_table"],
                "function_name": r.get("function_name", ""),
            })
    for name, table in sql.get("triggers", {}).items():
        if name not in seen_trg:
            seen_trg.add(name)
            merged["triggers"].append({
                "trigger_name": name,
                "on_table": table,
                "function_name": sql.get("trigger_fns", {}).get(name, ""),
            })
    # Fill in trigger -> function for triggers that came from the live DB
    # dump but whose function name only the SQL scan knows.
    for t in merged["triggers"]:
        if not t.get("function_name"):
            t["function_name"] = sql.get("trigger_fns", {}).get(t["trigger_name"], "")
    return merged


def _do_block(statements: list[str], kind: str) -> str:
    """Wrap statements in a DO block so they only run when the object exists."""
    body = "\n".join(f"        {s}" for s in statements)
    return (
        "DO $$\n"
        "DECLARE\n"
        "    _obj text;\n"
        "BEGIN\n"
        f"    -- {kind}\n"
        "    SELECT c.relname INTO _obj\n"
        "    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace\n"
        "    WHERE n.nspname = 'public' AND c.relname = $1;\n"
        "    IF _obj IS NOT NULL THEN\n"
        f"{body}\n"
        "    END IF;\n"
        "END $$;\n"
    )


def _rename_constraint_dob(old_table: str, new_table: str, pairs: list[tuple[str, str]]) -> str:
    if not pairs:
        return ""
    decls = "\n".join(f"    _con{i} text;" for i in range(len(pairs)))
    blocks = []
    for i, (old, new) in enumerate(pairs):
        blocks.append(
            f"    SELECT c.conname INTO _con{i} FROM pg_constraint c "
            f"JOIN pg_class t ON t.oid = c.conrelid "
            f"JOIN pg_namespace n ON n.oid = t.relnamespace "
            f"WHERE n.nspname='public' AND t.relname = '{new_table}' "
            f"AND c.conname = '{old}';\n"
            f"    IF _con{i} IS NOT NULL THEN\n"
            f"        EXECUTE format('ALTER TABLE public.%I RENAME CONSTRAINT %I TO %I',\n"
            f"                      '{new_table}', '{old}', '{new}');\n"
            f"    END IF;"
        )
    return (
        "DO $$\n"
        "DECLARE\n"
        f"{decls}\n"
        "BEGIN\n"
        + "\n".join(blocks)
        + "\n"
        "END $$;\n"
    )


def _rename_trigger_dob(new_table: str, pairs: list[tuple[str, str]]) -> str:
    if not pairs:
        return ""
    bodies = []
    for old, new in pairs:
        bodies.append(
            f"        IF EXISTS (SELECT 1 FROM pg_trigger tg "
            f"JOIN pg_class c ON c.oid = tg.tgrelid "
            f"JOIN pg_namespace n ON n.oid = c.relnamespace "
            f"WHERE n.nspname='public' AND c.relname='{new_table}' AND tg.tgname='{old}' "
            f"AND NOT tg.tgisinternal) THEN\n"
            f"            EXECUTE format('ALTER TRIGGER %I ON public.%I RENAME TO %I',\n"
            f"                          '{old}', '{new_table}', '{new}');\n"
            f"        END IF;"
        )
    return (
        "DO $$\n"
        "BEGIN\n"
        + "\n".join(bodies)
        + "\n"
        "END $$;\n"
    )


def _rename_function_dob(pairs: list[tuple[str, str]]) -> str:
    if not pairs:
        return ""
    bodies = []
    for old, new in pairs:
        bodies.append(
            f"        IF EXISTS (SELECT 1 FROM pg_proc p "
            f"JOIN pg_namespace n ON n.oid = p.pronamespace "
            f"WHERE n.nspname='public' AND p.proname='{old}') THEN\n"
            f"            EXECUTE format('ALTER FUNCTION public.%I() RENAME TO %I',\n"
            f"                          '{old}', '{new}');\n"
            f"        END IF;"
        )
    return (
        "DO $$\n"
        "BEGIN\n"
        + "\n".join(bodies)
        + "\n"
        "END $$;\n"
    )


def build_migration(old: str, new: str, objects: dict, number: int, stem: str) -> str:
    indexes = [r["index_name"] for r in objects.get("indexes", []) if r["on_table"] == old]
    constraints = [r for r in objects.get("constraints", []) if r["on_table"] == old]
    triggers = [r for r in objects.get("triggers", []) if r["on_table"] == old]

    # Constraint-backed indexes are renamed by RENAME CONSTRAINT, not by
    # ALTER INDEX — renaming the constraint also renames its backing index.
    constraint_names = {c["constraint_name"] for c in constraints}
    plain_indexes = [i for i in indexes if i not in constraint_names]

    seq_names = [
        s["sequence_name"] for s in objects.get("sequences", [])
        if s["sequence_name"].startswith(old + "_")
    ]

    out: list[str] = []
    out.append(HEADER.format(stem=f"{number:03d}_{stem}", old=old, new=new))
    out.append("")
    out.append("-- ── 1. Rename the table ────────────────────────────────────────────")
    out.append("")
    out.append(f"ALTER TABLE IF EXISTS {old} RENAME TO {new};")
    out.append("")

    if plain_indexes:
        out.append("-- ── 2. Rename dependent indexes (name-only) ─────────────────────────")
        out.append("")
        for i in sorted(plain_indexes):
            ni = rename_db_object(i)
            if ni == i:
                continue
            out.append(f"-- {i} -> {ni}")
            out.append(f"ALTER INDEX IF EXISTS {i} RENAME TO {ni};")
        out.append("")

    if constraints:
        out.append("-- ── 3. Rename dependent constraints (name-only) ───────────────────")
        out.append("")
        pairs = []
        for c in sorted(constraints, key=lambda c: c["constraint_name"]):
            oc = c["constraint_name"]
            nc = rename_db_object(oc)
            if oc == nc:
                continue
            pairs.append((oc, nc))
            out.append(f"-- {oc} -> {nc}")
        out.append("")
        out.append(_rename_constraint_dob(old, new, pairs))

    if seq_names:
        out.append("-- ── 4. Rename owned sequences (name-only) ─────────────────────────")
        out.append("")
        for s in sorted(seq_names):
            ns = rename_db_object(s)
            if ns == s:
                continue
            out.append(f"-- {s} -> {ns}")
            out.append(f"ALTER SEQUENCE IF EXISTS {s} RENAME TO {ns};")
        out.append("")

    if triggers:
        out.append("-- ── 5. Rename triggers and their functions (name-only) ────────────")
        out.append("")
        tpairs = []
        fpairs = []
        for t in sorted(triggers, key=lambda t: t["trigger_name"]):
            ot = t["trigger_name"]
            nt = rename_db_object(ot)
            if ot != nt:
                tpairs.append((ot, nt))
                out.append(f"-- trigger {ot} -> {nt}")
            of = t["function_name"]
            nf = rename_db_object(of)
            if of != nf:
                fpairs.append((of, nf))
                out.append(f"-- function {of} -> {nf}")
        out.append("")
        if tpairs:
            out.append(_rename_trigger_dob(new, tpairs))
        if fpairs:
            out.append(_rename_function_dob(fpairs))

    out.append("-- ── 6. Verify ────────────────────────────────────────────────────")
    out.append("--")
    out.append("-- SELECT to_regclass('public." + new + "') AS new_table;   -- must be non-NULL")
    out.append("-- SELECT to_regclass('public." + old + "') AS old_table;   -- must be NULL")
    out.append("")
    out.append("DO $$")
    out.append("BEGIN")
    out.append(f"    IF to_regclass('public.{old}') IS NOT NULL THEN")
    out.append(f"        RAISE EXCEPTION 'prefix unification incomplete: public.{old} still exists';")
    out.append("    END IF;")
    out.append(f"    IF to_regclass('public.{new}') IS NULL THEN")
    out.append(f"        RAISE EXCEPTION 'prefix unification failed: public.{new} missing';")
    out.append("    END IF;")
    out.append("END $$;")
    out.append("")
    out.append("-- ── ROLLBACK ──────────────────────────────────────────────────────")
    out.append("--")
    out.append("--   Reverse the rename.  Run these blocks in REVERSE file order")
    out.append("--   (096 -> 090) to restore the pre-unification names.  Every")
    out.append("--   statement is guarded, so the rollback is safe to re-run and")
    out.append("--   safe on a database where an object was never created.")
    out.append("--")
    out.append("-- >>> ROLLBACK-SQL-BEGIN")
    out.append(f"--   ALTER TABLE IF EXISTS {new} RENAME TO {old};")
    if plain_indexes:
        out.append("--")
        for i in sorted(plain_indexes):
            ni = rename_db_object(i)
            if ni == i:
                continue
            out.append(f"--   ALTER INDEX IF EXISTS {ni} RENAME TO {i};")
    if constraints:
        pairs = [
            (c["constraint_name"], rename_db_object(c["constraint_name"]))
            for c in sorted(constraints, key=lambda c: c["constraint_name"])
            if rename_db_object(c["constraint_name"]) != c["constraint_name"]
        ]
        if pairs:
            out.append("--")
            for oc, nc in pairs:
                out.append(f"--   {nc} -> {oc}")
            out.append("--")
            out.append(_rename_constraint_dob(new, old, [(nc, oc) for oc, nc in pairs]))
    if seq_names:
        out.append("--")
        for s in sorted(seq_names):
            ns = rename_db_object(s)
            if ns == s:
                continue
            out.append(f"--   ALTER SEQUENCE IF EXISTS {ns} RENAME TO {s};")
    if triggers:
        tpairs = []
        fpairs = []
        for t in sorted(triggers, key=lambda t: t["trigger_name"]):
            ot = t["trigger_name"]
            nt = rename_db_object(ot)
            if ot != nt:
                tpairs.append((nt, ot))
            of = t.get("function_name") or ""
            nf = rename_db_object(of)
            if of and of != nf:
                fpairs.append((nf, of))
        if tpairs:
            out.append("--")
            for nt, ot in tpairs:
                out.append(f"--   {nt} -> {ot}")
            out.append("--")
            out.append(_rename_trigger_dob(new, tpairs))
        if fpairs:
            out.append("--")
            for nf, of in fpairs:
                out.append(f"--   {nf}() -> {of}()")
            out.append("--")
            out.append(_rename_function_dob(fpairs))
    out.append("-- <<< ROLLBACK-SQL-END")
    out.append("--")
    out.append(f"-- ROLLBACK COMPLETE for {new}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db-objects", default=None)
    ap.add_argument("--sql-objects", default=None)
    ap.add_argument("--out-dir", default=str(ROOT / "db" / "migrations"))
    args = ap.parse_args()

    db_objects = _load_objects(Path(args.db_objects) if args.db_objects else None)
    sql_objects = _load_objects(Path(args.sql_objects) if args.sql_objects else None)
    objects = _merge_objects(db_objects, sql_objects)

    out_dir = Path(args.out_dir)
    # Remove any previously generated unification migrations so the numbering
    # is always derived from the last *real* migration.
    for stale in out_dir.glob("*_unify_rename_*.sql"):
        stale.unlink()
    existing = sorted(p.name for p in out_dir.glob("*.sql"))
    nums = []
    for n in existing:
        head = n.split("_", 1)[0]
        if head.isdigit():
            nums.append(int(head))
    start = (max(nums) if nums else 0) + 1

    written = []
    for i, (old, stem) in enumerate(FILE_STEMS):
        new = TABLE_MAP[old]
        num = start + i
        fname = f"{num:03d}_{stem}.sql"
        body = build_migration(old, new, objects, num, stem)
        (out_dir / fname).write_text(body, encoding="utf-8")
        written.append(fname)
        print(f"wrote {fname}  ({old} -> {new})")

    print()
    print("Migration files created:")
    for f in written:
        print(f"  db/migrations/{f}")
    return 0


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    raise SystemExit(main())
